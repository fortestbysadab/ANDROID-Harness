package com.androidharness.core

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Where the API key lives.
 *
 * The obvious choice would have been `EncryptedSharedPreferences`, and
 * it is the wrong one now: Jetpack Security Crypto was deprecated at
 * 1.1.0 in 2025, with no replacement planned, and its own deprecation
 * note points at "existing platform APIs and direct use of Android
 * Keystore". Google's suggested successor is DataStore plus Tink, which
 * is a large dependency for a single short string.
 *
 * So this is what the deprecation notice describes, directly: an AES-GCM
 * key generated inside the Android Keystore, and the ciphertext stored
 * in ordinary preferences. The key material never leaves the Keystore
 * and cannot be extracted by this app, let alone another one. On devices
 * with a secure element it is held there.
 *
 * What this does and does not protect against, stated plainly because
 * "encrypted" is a word that invites over-confidence: it protects the
 * key at rest, against another app reading the preferences file or
 * against someone pulling the file off the device. It does not protect
 * against a compromised copy of this app, which can simply ask the
 * Keystore to decrypt - no local storage scheme can.
 */
object SecretStore {

    private const val PREFERENCES = "harness-secrets"
    private const val KEYSTORE = "AndroidKeyStore"
    private const val KEY_ALIAS = "harness-secret-key"
    private const val TRANSFORMATION = "AES/GCM/NoPadding"
    private const val GCM_TAG_BITS = 128
    private const val SEPARATOR = ":"

    fun put(context: Context, name: String, value: String) {
        val preferences = context.getSharedPreferences(PREFERENCES, Context.MODE_PRIVATE)
        if (value.isEmpty()) {
            preferences.edit().remove(name).apply()
            return
        }
        val cipher = Cipher.getInstance(TRANSFORMATION).apply { init(Cipher.ENCRYPT_MODE, key()) }
        val ciphertext = cipher.doFinal(value.toByteArray(Charsets.UTF_8))
        // The IV is generated by the cipher and must be stored with the
        // ciphertext. It is not secret; reusing one would be the bug.
        val encoded = encode(cipher.iv) + SEPARATOR + encode(ciphertext)
        preferences.edit().putString(name, encoded).apply()
    }

    fun get(context: Context, name: String): String {
        val stored = context
            .getSharedPreferences(PREFERENCES, Context.MODE_PRIVATE)
            .getString(name, null)
            ?: return ""
        val parts = stored.split(SEPARATOR)
        if (parts.size != 2) return ""
        return try {
            val cipher = Cipher.getInstance(TRANSFORMATION).apply {
                init(Cipher.DECRYPT_MODE, key(), GCMParameterSpec(GCM_TAG_BITS, decode(parts[0])))
            }
            String(cipher.doFinal(decode(parts[1])), Charsets.UTF_8)
        } catch (failure: Exception) {
            // The Keystore entry can genuinely disappear - a restored
            // backup, or the screen lock being removed on some devices.
            // An unreadable secret is an absent secret, not a crash.
            ""
        }
    }

    fun isSet(context: Context, name: String): Boolean = get(context, name).isNotEmpty()

    private fun key(): SecretKey {
        val keystore = KeyStore.getInstance(KEYSTORE).apply { load(null) }
        (keystore.getEntry(KEY_ALIAS, null) as? KeyStore.SecretKeyEntry)?.let { return it.secretKey }

        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, KEYSTORE)
        generator.init(
            KeyGenParameterSpec.Builder(
                KEY_ALIAS,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                // Deliberately not requiring device unlock: scheduled
                // tasks have to run while the phone is locked in a
                // pocket, and a key the agent cannot use at 3 a.m. is a
                // feature that does not work.
                .setUserAuthenticationRequired(false)
                .build(),
        )
        return generator.generateKey()
    }

    private fun encode(bytes: ByteArray): String = Base64.encodeToString(bytes, Base64.NO_WRAP)

    private fun decode(text: String): ByteArray = Base64.decode(text, Base64.NO_WRAP)
}
